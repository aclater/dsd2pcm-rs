/*
 * Reference for dsd2pcm's `Filter::Pysacd`: pysacd's filter (pysacd/dsp.c, unchanged) run as
 * one stream per area, and the 24-bit quantiser of pysacd's process_batch() with the dither
 * seeded per frame. Built by gen.sh with `-O2 -ffp-contract=off` (pysacd's `ref` build).
 *
 *   pysacd_ref taps
 *       Rust source of the filter constants (src/filters/pysacd_taps.rs).
 *   pysacd_ref gen KIND CH FRAMES OUT.dsd
 *       Test input: FRAMES Super Audio CD frames of CH channels, interleaved byte by byte.
 *       KIND: silence, ff, music (two integer sines through a 1-bit modulator), random.
 *   pysacd_ref run IN.dsd CH RATE GAIN_DB TC0 OUT.i32 OUT.f32 [batch]
 *       Converts the input as one area starting at frame TC0. OUT.i32: the kept samples,
 *       interleaved, little-endian int32. OUT.f32: the same samples before quantising, as
 *       float32. `batch` seeds the dither once at TC0 (pysacd's process_batch() with the
 *       whole input as one batch) instead of once per frame.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "pysacd/dsp.c"

static inline uint32_t xorshift(uint32_t *s)
{
    uint32_t x = *s;
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    return *s = x;
}

static uint32_t seed(uint32_t tc)
{
    return 0x9E3779B9u ^ (tc * 2654435761u);
}

static void put32(FILE *f, uint32_t v)
{
    uint8_t b[4] = {(uint8_t)v, (uint8_t)(v >> 8), (uint8_t)(v >> 16), (uint8_t)(v >> 24)};
    fwrite(b, 1, 4, f);
}

static uint64_t fnv(uint64_t h, uint32_t v)
{
    for (int i = 0; i < 4; i++) {
        h ^= (v >> (8 * i)) & 0xff;
        h *= 0x100000001b3ull;
    }
    return h;
}

static int taps(void)
{
    double h1[S1_TAPS];
    dsd2pcm_t *d88 = calloc(1, sizeof(*d88)), *d176 = calloc(1, sizeof(*d176));
    if (!d88 || !d176 || dsd2pcm_init(d88, 1, 88200) < 0 || dsd2pcm_init(d176, 1, 176400) < 0)
        return 1;
    kaiser_lowpass(h1, S1_TAPS, 162300.0 / 2822400.0, 110);
    uint64_t h = 0xcbf29ce484222325ull;
    for (int j = 0; j < S1_BYTES; j++)
        for (int v = 0; v < 256; v++) {
            union { float f; uint32_t u; } w = {d88->s1_lut[j][v]};
            h = fnv(h, w.u);
        }
    printf("// SPDX-License-Identifier: MIT OR Apache-2.0\n"
           "// Generated by tests/pysacd-ref/gen.sh from pysacd's dsp.c (commit 94b2c53); do not edit.\n"
           "//! The constants of pysacd's DSD64 to PCM filter, as `dsd2pcm_init` computes them\n"
           "//! (Kaiser-windowed low-pass filters).\n\n");
    printf("/// Stage 1 taps (`double`, before the byte tables), oldest first.\n"
           "pub(super) const H1: [u64; %d] = [\n", S1_TAPS);
    for (int i = 0; i < S1_TAPS; i++) {
        union { double f; uint64_t u; } w = {h1[i]};
        printf("    0x%016llx,\n", (unsigned long long)w.u);
    }
    printf("];\n\n/// Stage 2 taps (`float`).\npub(super) const H2: [u32; %d] = [\n", S2_TAPS);
    for (int i = 0; i < S2_TAPS; i++) {
        union { float f; uint32_t u; } w = {d88->s2[0].h[i]};
        printf("    0x%08x,\n", w.u);
    }
    printf("];\n\n/// Stage 3 taps (`float`).\npub(super) const H3: [u32; %d] = [\n", S3_TAPS);
    for (int i = 0; i < S3_TAPS; i++) {
        union { float f; uint32_t u; } w = {d88->s3[0].h[i]};
        printf("    0x%08x,\n", w.u);
    }
    printf("];\n\n/// FNV-1a (64-bit) of the stage 1 byte tables' `float` bits, table by table.\n"
           "#[cfg(test)]\npub(super) const LUT_FNV: u64 = 0x%016llx;\n\n", (unsigned long long)h);
    printf("/// Group delay in output samples at 88.2 kHz and 176.4 kHz.\n"
           "pub(super) const DELAY: [usize; 2] = [%d, %d];\n", d88->delay, d176->delay);
    return 0;
}

/* Test inputs: integer arithmetic only, so that the Rust tests make the same bytes. */
static int gen(const char *kind, int ch, int frames, const char *path)
{
    size_t n = (size_t)frames * FRAME_BYTES_PER_CH;
    uint8_t *buf = malloc(n * ch);
    if (!buf)
        return 1;
    for (int c = 0; c < ch; c++) {
        /* two "magic circle" oscillators, about 1 kHz and 7 kHz, 1/4 of full scale each */
        int64_t x1 = 1 << 22, y1 = (int64_t)c << 20, x2 = 1 << 22, y2 = -((int64_t)c << 20);
        const int64_t k1 = 2390000, k2 = 16730000;
        int64_t integ = 0, prev = 1 << 24;
        uint64_t r = 0x9E3779B97F4A7C15ull ^ (uint64_t)(c + 1);
        for (size_t i = 0; i < n; i++) {
            uint8_t byte = 0;
            if (!strcmp(kind, "silence"))
                byte = DSD_SILENCE;
            else if (!strcmp(kind, "ff"))
                byte = 0xff;
            else if (!strcmp(kind, "random")) {
                r ^= r << 13;
                r ^= r >> 7;
                r ^= r << 17;
                byte = (uint8_t)(r >> 32);
            } else if (!strcmp(kind, "music")) {
                for (int b = 0; b < 8; b++) {
                    x1 -= (k1 * y1) >> 30;
                    y1 += (k1 * x1) >> 30;
                    x2 -= (k2 * y2) >> 30;
                    y2 += (k2 * x2) >> 30;
                    integ += x1 + x2 - prev;
                    int bit = integ >= 0;
                    prev = bit ? (1 << 24) : -(1 << 24);
                    byte = (uint8_t)(byte << 1 | bit);
                }
            } else {
                fprintf(stderr, "unknown kind %s\n", kind);
                return 2;
            }
            buf[i * ch + c] = byte;
        }
    }
    FILE *f = fopen(path, "wb");
    if (!f || fwrite(buf, 1, n * ch, f) != n * ch || fclose(f))
        return 1;
    free(buf);
    return 0;
}

static int run(int argc, char **argv)
{
    int ch = atoi(argv[3]), rate = atoi(argv[4]);
    double gain_db = atof(argv[5]);
    uint32_t tc0 = (uint32_t)strtoul(argv[6], NULL, 0);
    int batch = argc > 9 && !strcmp(argv[9], "batch");
    if (ch < 1 || ch > MAX_CHANNELS_SACD || (rate != 88200 && rate != 176400))
        return 2;
    size_t fb = (size_t)ch * FRAME_BYTES_PER_CH;
    FILE *fi = fopen(argv[2], "rb");
    if (!fi)
        return 1;
    fseek(fi, 0, SEEK_END);
    long sz = ftell(fi);
    fseek(fi, 0, SEEK_SET);
    if (sz <= 0 || (size_t)sz % fb)
        return 1;
    int nf = (int)((size_t)sz / fb);
    uint8_t *dsd = malloc((size_t)sz), *silence = malloc(fb);
    dsd2pcm_t *dsp = malloc(sizeof(*dsp));
    if (!dsd || !silence || !dsp || fread(dsd, 1, (size_t)sz, fi) != (size_t)sz)
        return 1;
    fclose(fi);
    memset(silence, DSD_SILENCE, fb);
    if (dsd2pcm_init(dsp, ch, rate) < 0)
        return 1;
    FILE *fq = fopen(argv[7], "wb"), *ff = fopen(argv[8], "wb");
    if (!fq || !ff)
        return 1;

    /* process_batch() of pysacd's sacdconv.c, as one stream (no reset), with the dither
       seeded at the start of every frame of output (or once, with `batch`). */
    int opf = dsp->out_per_frame;
    uint32_t skip = (uint32_t)dsp->delay;
    uint32_t keep = (uint32_t)nf * opf, got = 0, pos = 0;
    uint32_t rng = seed(tc0);
    const float scale = 8388607.0f * (float)pow(10.0, gain_db / 20.0);
    const float lsb = 1.0f / 4294967296.0f;
    for (int i = 0; got < keep; i++) {
        dsd2pcm_frame(dsp, i < nf ? dsd + (size_t)i * fb : silence);
        for (int s = 0; s < opf && got < keep; s++, pos++) {
            if (pos < skip)
                continue;
            if (!batch && got % opf == 0)
                rng = seed(tc0 + got / opf);
            for (int c = 0; c < ch; c++) {
                /* GCC evaluates the left call first; spelled out so that it is defined */
                uint32_t a = xorshift(&rng);
                uint32_t b = xorshift(&rng);
                float dith = ((float)a - (float)b) * lsb;
                long v = lrintf(dsp->out[c][s] * scale + dith);
                put32(fq, (uint32_t)(int32_t)(v > 8388607 ? 8388607 : v < -8388608 ? -8388608 : v));
                union { float f; uint32_t u; } w = {dsp->out[c][s]};
                put32(ff, w.u);
            }
            got++;
        }
    }
    fclose(fq);
    fclose(ff);
    dsd2pcm_free(dsp);
    free(dsp);
    free(dsd);
    free(silence);
    return 0;
}

int main(int argc, char **argv)
{
    if (argc == 2 && !strcmp(argv[1], "taps"))
        return taps();
    if (argc == 6 && !strcmp(argv[1], "gen"))
        return gen(argv[2], atoi(argv[3]), atoi(argv[4]), argv[5]);
    if ((argc == 9 || argc == 10) && !strcmp(argv[1], "run"))
        return run(argc, argv);
    fprintf(stderr, "usage: see the comment at the top of pysacd_ref.c\n");
    return 2;
}
